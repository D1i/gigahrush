const meta = (tags: string[], weight: number, note: string) => ({ tags: [...tags, ONLY], gen: { weight, min: 0, max: 99 }, elite: NONE, note });
/** Своя высота потолка комнаты (Room.ceilM). */
function ceil(r: Room, m: number): Room {
  r.ceilM = m;
  return r;
}

// ─────────────────────────────── Станция: масштабы ───────────────────────────────

/** Масштаб станции поперёк оси (x): путь у стены, платформа, ряд пилонов, неф посередине — и зеркально. */
interface Scale {
  /** ширина зала, м */
  W: number;
  /** ширина пути и платформы до ряда пилонов, м */
  track: number;
  plat: number;
  /** пилон: поперёк × вдоль оси, м; шаг пилонов вдоль оси, м */
  col: [number, number];
  pitch: number;
  /** пропы: путь (9 м), кромка платформы (ширина), панно путевой стены (ширина) */
  trackP: string;
  edgeP: string;
  edgeW: number;
  panelP: string;
  panelW: number;
}

/** Большой зал 18 м: путь 3.0, платформа 2.2, пилоны 0.8×1.2 через 4.5 м, неф 6.0. */
const BIG: Scale = { W: 18, track: 3, plat: 2.2, col: [0.8, 1.2], pitch: 4.5, trackP: 'p_metro_track', edgeP: 'p_metro_edge', edgeW: 0.4, panelP: 'p_metro_panel', panelW: 2.4 };
/** Станция поменьше 9 м — вдвое мельче: неф 3.0 (во всю ширину перехода). */
const MINI: Scale = { W: 9, track: 1.5, plat: 1.1, col: [0.4, 0.6], pitch: 2.25, trackP: 'p_metro_mini_track', edgeP: 'p_metro_mini_edge', edgeW: 0.2, panelP: 'p_metro_mini_panel', panelW: 1.2 };
/** Крошечная станция 4.6 м — вчетверо мельче: неф 1.6 (во всю ширину служебного хода). */
const MICRO: Scale = { W: 4.6, track: 0.75, plat: 0.55, col: [0.2, 0.3], pitch: 1.125, trackP: 'p_metro_micro_track', edgeP: 'p_metro_micro_edge', edgeW: 0.1, panelP: 'p_metro_micro_panel', panelW: 0.6 };

/** Левый край западного и восточного рядов пилонов, м. */
const colsX = (S: Scale): [number, number] => [S.track + S.plat, S.W - S.track - S.plat - S.col[0]];
/** Неф: от западного ряда пилонов до восточного, м. */
const nave = (S: Scale): [number, number] => [S.track + S.plat + S.col[0], S.W - S.track - S.plat - S.col[0]];

/** Ряд пилонов (вырезы пола — колонны на всю высоту) у x0 на отрезке оси [y0, y0 + len): len / шаг пилонов, крайние —
 *  на одном отступе от концов (полшага без пилона, вниз до клетки), остальные — поровну между ними: ряд симметричен,
 *  кусок, повёрнутый на 180°, встаёт пилонами туда же (большой зал: y 1.6–2.8 и 6.2–7.4). */
function pillars(b: RoomBuilder, S: Scale, x0: number, y0: number, len: number): RoomBuilder {
  const [cw, ch] = S.col;
  const n = Math.max(1, Math.round(len / S.pitch));
  const m = Math.floor(((S.pitch - ch) / 2) * 10 + 1e-6) / 10;
  const step = n > 1 ? (len - 2 * m - ch) / (n - 1) : 0;
  for (let k = 0; k < n; k++) b.cut(x0, y0 + m + k * step, cw, ch);
  return b;
}

/** Путь с кромкой платформы у западной (W) или восточной (E) путевой стены на 9-метровом отрезке оси от y0. */
function track(b: RoomBuilder, S: Scale, side: 'W' | 'E', y0: number): RoomBuilder {
  const w = side === 'W';
  return b
    .put(S.trackP, w ? S.track / 2 : S.W - S.track / 2, y0 + 4.5, w ? 0 : 180)
    .put(S.edgeP, w ? S.track + S.edgeW / 2 : S.W - S.track - S.edgeW / 2, y0 + 4.5, w ? 0 : 180);
}

/** Панно на путевой стене: по центрам ys (м вдоль оси). Ставится как wall() (задом к стене, отступ — до полуклетки
 *  «от стены»), но без обхода всех клеток комнаты — залы большие. */
function panels(b: RoomBuilder, S: Scale, side: 'W' | 'E', ys: number[]): RoomBuilder {
  const d = PROP_BY_ID[S.panelP]?.h ?? 0.1;
  const x = side === 'W' ? Math.ceil(d * 10 - 1e-6) / 20 : Math.floor((S.W - d / 2) * 20 + 1e-6) / 20;
  for (const y of ys) b.put(S.panelP, x, y, side === 'W' ? 270 : 90);
  return b;
}


/**
 * Пролёт станции 9 м от y0 по оси: пути и кромки у обеих путевых стен, два ряда пилонов, свет — кессоны над нефом
 * (большой зал — два в ряд, поменьше — один) или полоса (крошечная), полосы над платформами (кроме крошечной).
 */
function bay(b: RoomBuilder, S: Scale, y0: number): RoomBuilder {
  const [c0, c1] = colsX(S);
  const [n0, n1] = nave(S);
  track(b, S, 'W', y0);
  track(b, S, 'E', y0);
  pillars(b, S, c0, y0, 9);
  pillars(b, S, c1, y0, 9);
  for (const y of [y0 + 2.25, y0 + 6.75]) {
    if (S === BIG) b.put('p_metro_light', (n0 + n1) / 2 - 1.5, y).put('p_metro_light', (n0 + n1) / 2 + 1.5, y);
    else if (S === MINI) b.put('p_metro_light', (n0 + n1) / 2, y);
    else b.put('p_metro_light_strip', (n0 + n1) / 2, y);
    if (S !== MICRO) b.put('p_metro_light_strip', S.track + S.plat / 2, y).put('p_metro_light_strip', S.W - S.track - S.plat / 2, y);
  }
  return b;
}

