// Метро — бесконечная станция (биом «Метро», layout 'tunnels'; рост — src/gen4d/stream.ts, правила —
// docs/GENERATOR-4D.md §17, §24). Замысел заказчика: «бесконечная станция метро из фракталов и бесконечных ответвлений,
// эскалаторы, с низким шансом могут сорваться и упасть». Образ — советская колонная станция: белый мрамор, пилоны,
// гранитный пол с красно-серыми ромбами, кессоны со световыми полосами, мозаичные панно на путевых стенах, пути сбоку за
// рядом пилонов; редкий сгоревший зал у эскалатора (Кингс-Кросс: обугленные балюстрады, копоть).
//
// Три сети (метки — src/data/roomBuilder.ts, наборы сетей — src/gen4d/biomes.ts), у каждой своя станция — «станции
// внутри станций», та же отделка и те же панно, только мельче:
//  • 'metro_hall' — ось зала станции во всю его ширину 17.6 м: куски зала 18×9 м стыкуются торцами, пролёт за пролётом;
//    станция — большой зал (пути 3 м по бокам, платформы, ряды пилонов 0.8×1.2 через 4.5 м, неф 6 м, потолок 4.5);
//  • 'metro_per' — переходы 3.0 м (потолок 3.2): прямые, повороты, тройники, лестничные сходы на этаж; станция
//    поменьше metro_mini_9 (9 м шириной, пилоны 0.4) — кусок прямой этой сети;
//  • 'metro_slu' — служебные ходы 1.6 м (потолок 2.5): по бокам двери служебных помещений ('slu>room', как кладовые
//    подвала: за дверью с шансом tunnels.storage — дежурная, щитовая, машинный зал эскалатора, комната отдыха);
//    крошечная станция metro_micro_9 (4.6 м шириной, пилоны 0.2, «игрушечные» рельсы) — кусок прямой этой сети.
// Ветвление (двери между сетями растут всегда, как служебка общаги): зал → переход — проём 'hall>per' в путевой стене
// (через пути) пролёта metro_hall_9p, с той стороны — прямой кусок перехода с боковым проёмом 'per>hall'
// (metro_per_from_hall; он же из перехода ведёт в зал); переход → служебный ход — дверь 'per>slu' / 'slu>per'
// (metro_per_slu ↔ metro_slu_door, тоже в обе стороны); переход → эскалатор: зал у эскалатора (metro_esc_hall*, проём
// 'hall>esc') — тоннель (торцы 'esc>hall') — зал у эскалатора этажом выше или ниже — переходы дальше. Метки эскалатора
// направленные: тоннель встаёт только между залами, два тоннеля или два зала у эскалатора друг к другу не встают.
// Хабы — вестибюли с выходом в город ('stair' — закрытый выход сети, как двери вахты общаги): metro_vest (переходы) и
// metro_vest_hall (аванзал в торце зала: и проход 'metro_hall', и переходы) — хаб есть у всех сетей, кроме служебной.
// Бесконечность: частые бесконечные прямые участки (шов 4D, нужен тройник сети: metro_hall_T, metro_per_T,
// metro_slu_T) и кольца из вестибюлей.
//
// Размеры — до 18×18 м и тоннель 19 м: предел обзора биома Biome.sightM 28 м (свой, у мира — 9 м); тег 'длинный' — у
// комнат, где прямой отрезок пола длиннее 9 м (его проверяет только тест пресетов). Пути и кромки платформ — плоские
// пропы на уровне пола (проходимы). Свои высоты потолка (Room.ceilM): залы и вестибюли 4.5, у эскалатора 3.5, переходы
// и станция поменьше 3.2, служебные — обычные 2.5; высота проёмов — по метке (TAG_OPEN_H).
//
// Эскалаторный тоннель metro_esc_tunnel — план 6.0×19.0 м, Room.stair собран вручную: верхняя площадка y 0–2.5 на
// +8.1 (три этажа по 2.7) во всю ширину; три марша style 'escalator' (вверх — север, 14 м, ~30°) по x 0.4–1.6, 2.4–3.6,
// 4.4–5.6 (дорожки 1.2 м, между ними 0.8 м — балюстрады); нижняя площадка — пол комнаты y 16.5–19.0. Номер дорожки =
// индекс марша в stair.flights (0…2) — так их понимает механика эскалатора (src/locations/metroEscalator.ts). Пропов в
// тоннеле нет — обстановку рисует модуль метро. Короткий metro_esc_tunnel_s — подъём 5.4, марш 9.4 м.
//
// Теги: первый — 'метро' (группа спавна; отделка — по следующему тегу: правила 'метро' нет), затем вид помещения —
// 'зал' (большой зал, станции поменьше, залы у эскалатора), 'вестибюль', 'переход', 'эскалатор' (+ 'лестница'),
// 'сгоревший', 'служебное' (+ вид комнаты: 'дежурная', 'щитовая', 'машинная', 'отдых'); вид куска сети — 'ход' / 'хаб'
// (+ 'поворот', 'развилка'). У всех — 'только-биом': растут только в биоме «Метро».
