// Общага — сеть коридоров (биом «Общага», layout 'tunnels'; рост — src/gen4d/stream.ts, правила —
// docs/GENERATOR-4D.md §17, §22). Замысел заказчика: НЕ агрессивно неевклидовое советское общежитие — длинные
// коридоры, по бокам двери в маленькие тупиковые комнаты (одна дверь, очень бедно, 2–3 кровати); общие кухни,
// туалеты, душевая (комната закручена улиткой), прачечная; лестницы на этажи и спуск в подвал, затопленный по пояс;
// огромный вестибюль со столом вахтёра и комната вахтёра (кровать, телевизор). Коридоры — в бежевом и зелёном кафеле.
// На локации есть керосиновая лампа, которую можно подобрать (спот 'lantern').
//
// Сеть (как подвал и сарай): коридоры стыкуются меткой 'obshaga' во всю ширину коридора 2.0 м — прямые куски 1, 2,
// 3.6, 7.2, 9 м (с порогом-зазором — шаги 11, 21, 37, 73, 91 клетка: кольца добирают длину до клетки), поворот 2×2 м,
// развилка-тройник; хаб — вестибюль с вахтой ('stair' — двери на улицу, закрытый выход сети). По бокам коридоров:
//  • 'obshaga>room' — двери жилых комнат (боковые двери хода, как кладовые подвала: за дверью с шансом
//    tunnels.storage — комната, иначе дверь заперта). Это двери-створки, которые закрываются сами
//    (src/locations/obshaga.ts) и из которых вылезает рука: полотно — в комнате (room>obshaga), у коридора наличник;
//  • 'obshaga>common' — двери общих помещений (кухня, туалет, душевая, прачечная): растут всегда (как служебка);
//  • 'obshaga>stairs' — проём 2.0 м на лестничную клетку сбоку коридора (растёт всегда): лестницы не стоят в линии
//    коридора и не рвут прямые;
//  • 'hall>vahter' — дверь вестибюля в комнату вахтёра: будка посреди зала (комната встаёт в проём в полу вестибюля —
//    там ей ничто не мешает, она есть у каждого вестибюля).
// Прямые важнее всего (жалоба заказчика «прямых пространств маловато»): длинные куски 7.2 и 9 м — самые частые, вставок
// по 1 м мало, повороты и развилки редки, лестницы — сбоку. В «Прогулке» обзор в общаге — 45 м (Biome.viewM).
// Длина куска — не больше 9 м: предел обзора «Прогулки» 9 м исключает комнаты, внутри которых видно дальше (длинные
// коридоры складываются из кусков: обзор сквозь ходы и хабы не ограничен, §17.3); по той же причине вестибюль — 9×9 м
// с будкой вахтёра посередине (она рвёт диагонали).
//
// Лестничная клетка — зал 2.4×5.4 м с перепадом на этаж (Room.stair = straightStair, src/model/stairs.ts): нижняя
// площадка 0.9 м у южного проёма, марш 3.6 м во всю ширину, верхняя площадка 0.9 м на высоте этажа (2.7 м) у
// северного проёма. Клетка — за проёмом 'obshaga>stairs' сбоку коридора: наверх (за ней коридор этажа выше,
// Instance.z + 2.7), вниз (этаж ниже) или в подвал — внизу ход затопленного подвала 'obshaga_bsm' (1.6 м; с коридорами
// не стыкуется): подвал общаги — короткие ходы и бойлерная на этаж ниже коридора, наверх — той же лестницей.
//
// Теги: первый — 'общага' (группа спавна; отделка — по следующему тегу: правил 'общага' нет), затем вид помещения —
// 'коридор', 'комната', 'кухня', 'туалет', 'душ', 'прачечная', 'вахта', 'вахтёрская', 'лестница' (+ 'вверх' / 'вниз'),
// 'подвал' + 'затоплено' (вода по пояс — интеграция); вид куска сети — 'ход' / 'хаб' (+ 'поворот', 'развилка'). У всех
// — 'только-биом' (BIOME_ONLY_TAG): растут только в биоме «Общага» (biomeMul: только в биомах своей группы).
//
// Свет — плафоны и лампы ЛДС под потолком (p_obsh_plafond, p_obsh_tube: гаснут при отключении света), в коридорах —
// через 3.6–4.5 м. Керосиновая лампа — спот 'lantern' (группа 'lantern', содержимое — prop p_obsh_lantern): в комнате
// вахтёра всегда, в кухнях и жилых комнатах — редко (1 из 10).
