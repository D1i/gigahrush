/** Лестничная клетка 2.4×5.4 м на этаж (Room.stair, src/model/stairs.ts): нижняя площадка 0.9 м у южного проёма, марш
 *  во всю ширину 3.6 м (18 ступеней по 0.15 м, ~37°) к северу, верхняя площадка 0.9 м на высоте этажа у северного
 *  проёма. Клетка — сбоку коридора (проём 'obshaga>stairs' куска obsh_cor_9s), а не в его линии: лестницы не рвут
 *  прямые коридоры. up — из коридора наверх (за верхним проёмом — коридор этажа выше, Instance.z + 2.7), dn — вниз (этаж
 *  ниже), bsm — вниз в затопленный подвал (ход 'obshaga_bsm'). Наверх из подвала — та же клетка. */
function stair(kind: 'up' | 'dn' | 'bsm'): Room {
  const ids = { up: 'obsh_stair', dn: 'obsh_stair_dn', bsm: 'obsh_stair_down' } as const;
  const names = { up: 'Лестница общаги наверх', dn: 'Лестница общаги вниз', bsm: 'Лестница общаги в подвал' } as const;
  const notes = {
    up: 'Лестничная клетка 2.4×5.4 м сбоку коридора: из коридора — нижняя площадка 0.9 м, марш 3.6 м во всю ширину (18 ' +
      'ступеней по 0.15 м, перила) на этаж выше, верхняя площадка 0.9 м — там коридор следующего этажа.',
    dn: 'Лестничная клетка 2.4×5.4 м сбоку коридора: из коридора — верхняя площадка 0.9 м, марш 3.6 м на этаж вниз, ' +
      'нижняя площадка 0.9 м — там коридор этажа ниже.',
    bsm: 'Спуск в подвал 2.4×5.4 м сбоку коридора: верхняя площадка 0.9 м у коридора, марш 3.6 м на этаж вниз (18 ' +
      'ступеней по 0.15 м, перила), нижняя площадка 0.9 м у хода подвала 1.6 м — подвал на этаж ниже коридора.',
  } as const;
  const b = room(ids[kind], names[kind], {
    tags: ['общага', 'лестница', kind === 'up' ? 'вверх' : 'вниз', 'ход', ONLY],
    gen: { weight: kind === 'up' ? 0.5 : kind === 'dn' ? 0.3 : 0.45, min: 0, max: 99 },
    elite: NONE,
    note: notes[kind],
  })
    .rect(0, 0, 2.4, 5.4);
  // проём из коридора ('stairs>obshaga') — у той площадки, куда приходят из коридора; напротив — сеть дальше
  if (kind === 'up') b.open('N', 0.2, 'obshaga', 'Коридор этажа выше (верх марша)').open('S', 0.2, 'stairs>obshaga', 'Из коридора (низ марша)');
  else b.open('N', 0.2, 'stairs>obshaga', 'Из коридора (верх марша)');
  if (kind === 'dn') b.open('S', 0.2, 'obshaga', 'Коридор этажа ниже (низ марша)');
  if (kind === 'bsm') b.open('S', 0.4, 'obshaga_bsm', 'Ход подвала (низ марша)');
  const r = b
    .put('p_obsh_plafond', 1.2, 0.45)
    .put('p_obsh_plafond', 1.2, 4.95)
    .build();
  // марш с перепадом: верх (этаж) — у северной стены, низ (0) — у южной; ступени, перила, площадка — по описанию
  r.stair = straightStair({ w: 2.4, l: 5.4, up: 'N', landing: 0.9, top: 0.9 });
  return r;
}

