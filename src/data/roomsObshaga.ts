/** Спот керосиновой лампы: на полу (лампа — находка, модель стоит на полу). chance — доля вариантов с лампой. */
function lantern(b: RoomBuilder, x: number, y: number, chance: number): RoomBuilder {
  b.spot('lantern', 'Керосиновая лампа', x, y, 0, 'lantern');
  const lamp: Record<string, Fill> = { lantern: P('p_obsh_lantern') };
  return b.group('lantern', 'Керосиновая лампа', C_LAMP, chance >= 1 ? [[1, lamp]] : [[Math.round((1 - chance) / chance), {}], [1, lamp]]);
}

/** Мелочь в комнате (на тумбочке, на столе): спот 's', группа 'stash'. */
const STASH: Array<[number, Record<string, Fill>]> = [
  [6, {}],
  [2, { s: I('it_kopeyki') }],
  [1, { s: I('it_matches') }],
  [1, { s: I('it_canned') }],
  [1, { s: I('it_samogon') }],
];
function stash(b: RoomBuilder, x: number, y: number, name: string): RoomBuilder {
  return b.spot('s', name, x, y, 0, 'stash').group('stash', name, C_STASH, STASH);
}

