type SideDoor = ['W' | 'E', number, 'obshaga>room' | 'obshaga>common' | 'obshaga>stairs'];

/**
 * Кусок коридора 2.0 × len м (север — юг): проходы 'obshaga' во всю ширину, двери по бокам doors ([стена, от, метка]),
 * свет под потолком по оси через lamps (м от севера), extra — настенная мелочь.
 */
function corridor(id: string, name: string, len: number, weight: number, note: string, doors: SideDoor[], lamps: number[], extra?: (b: RoomBuilder) => void): Room {
  const b = room(id, name, {
    tags: ['общага', 'коридор', 'ход', ONLY],
    gen: { weight, min: 0, max: 99 },
    elite: NONE,
    note,
  })
    .rect(0, 0, COR, len)
    .open('N', 0, 'obshaga', 'Коридор (север)')
    .open('S', 0, 'obshaga', 'Коридор (юг)');
  let k = 0;
  for (const [side, at, tag] of doors) b.open(side, at, tag, tag === 'obshaga>room' ? `Комната ${++k}` : tag === 'obshaga>stairs' ? 'Лестничная клетка' : 'Общее помещение');
  // светильник ЛДС вдоль оси на длинных кусках, плафон — на коротких
  for (const y of lamps) b.put(len >= 7 ? 'p_obsh_tube' : 'p_obsh_plafond', COR / 2, y, len >= 7 ? 90 : 0);
  extra?.(b);
  return b.build();
}

