// ───────────────────────── построители ручек ─────────────────────────

type Spec = Omit<BeastKnob, 'group'>;
type More = Partial<Pick<BeastKnob, 'pct' | 'unit' | 'hint'>>;

/** Одна ручка. */
const n = (key: string, label: string, min: number, max: number, step: number, more: More = {}): Spec[] => [{ key, label, min, max, step, ...more }];
/** Пара [от, до] (ключи key.0 и key.1) — одной строкой на странице. */
const r = (key: string, label: string, min: number, max: number, step: number, more: More = {}): Spec[] =>
  [0, 1].map((i) => ({ key: `${key}.${i}`, label: `${label}, ${i ? 'до' : 'от'}`, min, max, step, range: label, ...more }));
/** Доля 0…1 в процентах. */
const p = (key: string, label: string, step = 0.01, hint?: string, min = 0, max = 1): Spec[] => n(key, label, min, max, step, { pct: true, ...(hint ? { hint } : {}) });
const group = (name: string, ...ks: Spec[][]): BeastKnob[] => ks.flat().map((k) => ({ ...k, group: name }));

const S = { unit: 'с' } as const;
const M = { unit: 'м' } as const;
const cfg = (o: object) => o as unknown as Record<string, unknown>;

