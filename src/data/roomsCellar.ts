// Погреб — земляные ходы под сараем (биом «Погреб», layout 'tunnels'; рост — src/gen4d/stream.ts, правила —
// docs/GENERATOR-4D.md §17, §25). Замысел заказчика: «Земляной погреб. Узкие пространства, осыпающаяся земля. Надо идти
// боком. Очень маленькие комнатки. Пыль, нет света». Нора-лабиринт: короткие ходы 0.6 м в чёрной земле, частые повороты
// и развилки, щели 0.4 м — только боком, крошечные камеры и клетушки, крепь из старых брёвен; света нет совсем (Biome.dark
// 1 — только фонарь игрока).
//
// Стен у комнат нет: оболочка — бугристая земля по плану комнаты (src/view3d/cellarMesh.ts), свод ~1.85 м в ходах и
// ~1.95 м в камерах; потолок болванки (2.5 м) в погребе не виден, поэтому подвесных («потолок») предметов здесь нет.
// Отделка (болванка, движок без оболочки) — земля (src/data/finishes.ts, f_cel_*). Поза боком, пыль, осыпи и обвалы —
// src/view3d/cellarWalk.ts (docs/LOCATIONS.md).
//
// Ширины (тело игрока в погребе — эллипс: плечи ±0.23 м, грудь ±0.13 м):
//  • ход — метка 'cellar' (0.6 м во всю ширину хода): лицом вперёд проходишь впритирку плечами;
//  • щель — середина «песочных часов» 0.4 м: только боком (лицом к стене, A/D). Щели — прямые куски хода (тег «щель»):
//    устья по 0.3 м во всю ширину хода (метки 'cellar' стыкуются), середина 0.4 м длиной 1.2–3.0 м. По весам щели —
//    больше половины прямых кусков: в погребе часто приходится идти боком;
//  • клетушка — сбоку от хода за щелью 0.4 м ('cellar>bin' ↔ 'bin>cellar', как кладовая подвала: за щелью с шансом
//    tunnels.storage клетушка, иначе щель заложена низкой дверцей).
// Куски: прямые 1, 2, 3 м (с порогом-зазором — шаги 1.1 … 3.7 м: кольца добирают длину), ход с уступом, ходы со щелью
// в клетушку, поворот (0.6 × 0.6 и Г 1.4 × 1.4), развилка Т и перекрёсток. Крепь (стойки по стенам хода, перемычка на
// 1.78 м) — через ~1 м в ходах и в устьях щелей. Хабы — крошечные камеры (1.6 × 2.0 … 2.0 × 2.2 м): три–четыре хода и
// лаз наверх ('stair' — закрытый выход сети; через него приходят в погреб из сарая — люк, src/locations/hatch.ts).
// Выход — камера «Дверь в снег» (хаб со спец-локацией SnowDoorSpec, растёт по правилу хабов: не ближе 40 м ходами от
// прошлой камеры, к 100 м — почти наверняка): в стене низкая дверь (метка с id SNOWDOOR_CONN), за ней снег — обвал
// засыпает, откопался — снежные тоннели (src/locations/snowDoor.ts). Переходов по счётчику в погребе нет (ownExit).
//
// Теги: первый — 'погреб' (группа спавна, отделка, закрытые двери погреба — src/blockout/doors.ts), затем вид куска:
// 'ход' (+ 'щель', 'поворот', 'развилка'), 'хаб', 'клетушка'. У всех — 'только-биом' (BIOME_ONLY_TAG): погреб растёт
// только в своём биоме, в прогонах и прежней прогулке его нет.
import type { Room, RoomElite } from '../model/types';
import { newSnowDoor, SNOWDOOR_CONN } from '../locations/storyDoors';
import { I, P, room, type RoomBuilder } from './roomBuilder';

const C_STASH = '#e76f51';
const NONE: RoomElite[] = [];
const ONLY = 'только-биом';
const CEL = 'погреб';
/** Ширина хода (метка 'cellar') и щели (середина «песочных часов», метка 'cellar>bin'), м. */
const W = 0.6;
const S = 0.4;
/** Устье щели во всю ширину хода, м. */
const STUB = 0.3;

const meta = (tags: string[], weight: number, note: string, elite: RoomElite[] = NONE) => ({
  tags: [CEL, ...tags, ONLY],
  gen: { weight, min: 0, max: 99 },
  elite,
  note,
});

/** Крепь поперёк хода, что идёт с севера на юг (rot 0), или с запада на восток (rot 90); narrow — над щелью 0.4 м. */
const frame = (b: RoomBuilder, x: number, y: number, rot: 0 | 90, narrow = false): RoomBuilder =>
  b.put(narrow ? 'p_cel_frame_narrow' : 'p_cel_frame', x, y, rot);

/** Места крепи по ходу длиной len, м: через ~1 м (середины равных частей). */
const along = (len: number): number[] => {
  const n = Math.floor(len / 1.2) + 1;
  return Array.from({ length: n }, (_, k) => Math.round(((k + 0.5) * len * 100) / n) / 100);
};

/** Что оставили в погребе: у стены камеры, в клетушке. */
const STASH: [number, Record<string, ReturnType<typeof I>>][] = [
  [5, {}],
  [2, { s: I('it_canned') }],
  [1, { s: I('it_matches') }],
  [1, { s: I('it_kopeyki') }],
];
const stash = (b: RoomBuilder, x: number, y: number, name = 'У стены'): RoomBuilder =>
  b.spot('s', name, x, y, 0, 's').group('s', name, C_STASH, STASH);

// ─────────────────────────────── Ходы и щели ───────────────────────────────

/** Прямой ход len м (север — юг) в крепи. */
function pass(id: string, name: string, len: number, weight: number, note: string): Room {
  const b = room(id, name, meta(['ход'], weight, note))
    .rect(0, 0, W, len)
    .open('N', 0, 'cellar', 'Ход (север)')
    .open('S', 0, 'cellar', 'Ход (юг)');
  for (const y of along(len)) frame(b, W / 2, y, 0);
  return b.build();
}

/** Щель — «песочные часы»: устья 0.6 × 0.3 м, середина 0.4 × mid м (только боком); крепь — в устьях середины. */
function squeeze(id: string, name: string, mid: number, weight: number, note: string): Room {
  const b = room(id, name, meta(['ход', 'щель'], weight, note))
    .rect(0, 0, W, STUB)
    .rect((W - S) / 2, STUB, S, mid)
    .rect(0, STUB + mid, W, STUB)
    .open('N', 0, 'cellar', 'Ход (север)')
    .open('S', 0, 'cellar', 'Ход (юг)');
  frame(b, W / 2, STUB + 0.05, 0, true);
  if (mid >= 2.4) frame(b, W / 2, STUB + mid / 2, 0, true);
  frame(b, W / 2, STUB + mid - 0.05, 0, true);
  return b.build();
}

