type CorDoor = ['W' | 'E', number, 'sanat>room' | 'sanat>proc'];

interface CorOpts {
  /** вид (теги после 'санаторий'), по умолчанию ['коридор'] */
  kind?: string[];
  /** двери по бокам: [стена, от (м от севера), метка] */
  doors?: CorDoor[];
  /** красная дорожка по оси (по умолчанию да) */
  runner?: boolean;
  /** плафоны по оси, м от севера (по умолчанию — через 4.5 м на 9 м, через 3 м короче) */
  lamps?: number[];
  /** обстановка: окна, банкетки, кадки */
  fill?: (b: RoomBuilder) => void;
}

/**
 * Прямой кусок коридора 3.0 × len м (север — юг): проходы 'sanat' во всю ширину на торцах, двери по бокам, красная
 * дорожка p_san_runner (1.2×3.0) по оси через 3 м — встык от торца до торца, плафоны под потолком.
 */
function corridor(id: string, name: string, len: number, weight: number, note: string, o: CorOpts): Room {
  const b = room(id, name, meta([...(o.kind ?? ['коридор']), 'ход'], weight, note))
    .rect(0, 0, COR, len)
    .open('N', 0, 'sanat', 'Коридор (север)')
    .open('S', 0, 'sanat', 'Коридор (юг)');
  let k = 0, q = 0;
  for (const [side, at, tag] of o.doors ?? []) b.open(side, at, tag, tag === 'sanat>room' ? `Палата ${++k}` : `Процедурная ${++q}`);
  if (o.runner !== false) for (let y = 1.5; y < len; y += 3) b.put('p_san_runner', COR / 2, y);
  const lamps = o.lamps ?? (len >= 9 ? [2.25, 6.75] : len >= 6 ? [1.5, 4.5] : [len / 2]);
  for (const y of lamps) b.put('p_san_ceiling_lamp', COR / 2, y);
  o.fill?.(b);
  return ceil(b.build(), CEIL_COR);
}

