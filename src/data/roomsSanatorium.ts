// Санаторий — евклидов биом без 4D-сдвигов (биом «Санаторий», layout 'tunnels', Biome.flat; рост — src/gen4d/stream.ts,
// контракт — tmp/sanatorium-wip/CONTRACT.md). Заказ: «Локация санаторий. Не 4D, а 3D локация. без 4D сдвигов». Образ —
// советский санаторий (референсы tmp/sanatorium-wip/ref/1..4.png): длинные коридоры-галереи с красной ковровой дорожкой
// по паркету «ёлочкой», окна с белым тюлем и бирюзовыми ламбрекенами, банкетки с красными подушками, фикусы и пальмы в
// кадках; водолечебница с кафельной ванной и панно «озеро и деревья»; бассейн под бетонными оболочками-сводами с высокими
// арочными окнами; палаты; комнаты в ремонте (ободранные стены, вскрытый пол, рулон линолеума). Существ и механик нет.
//
// Сеть: коридоры 3.0 м стыкуются меткой 'sanat' во всю ширину и на всю высоту коридора (3.3 м — TAG_OPEN_H, шва между
// кусками не видно) — прямые 9, 6 и 3 м (с порогом-зазором шаги 91, 61, 31 клетка), поворот и тройник 3×3 м; хабы —
// вестибюль 12×9 ('stair' на юге — двери «Выход к корпусам», закрытый выход сети) и бассейн 18×14. По бокам коридоров:
//  • 'sanat>room' — двери палат и комнат в ремонте (боковые двери хода, как кладовые подвала: за дверью с шансом
//    tunnels.storage — комната 'room>sanat', иначе дверь заперта);
//  • 'sanat>proc' — двери процедурных и общих помещений (водолечебница, грязелечебница, кабинет, душ Шарко, столовая,
//    процедурная в ремонте): растут всегда.
// Длинные прямые важнее всего (как в общаге): кускам 9 м — самый большой вес, смотришь вдоль коридора — 30–45 м до
// поворота. Здание — обычное трёхмерное (Biome.flat): комнаты биома не занимают в 3D место друг друга, поэтому размеры
// не ограничены пределом обзора (у биома sightM 0) — зал бассейна 18×14 и вестибюль 12×9 одним куском; тег 'длинный' —
// у комнат, где прямой отрезок пола длиннее 9 м (его проверяет только тест пресетов).
//
// Потолки (Room.ceilM): коридоры 3.3, вестибюль 4.2, бассейн 7.0, боковые помещения 3.0 (окно со шторой — 2.9 м),
// столовая 3.3. Двери боковых помещений — по умолчанию 2.1 м.
//
// Теги: первый — 'санаторий' (группа спавна; отделка — по следующему тегу: правила 'санаторий' нет), затем вид —
// 'коридор', 'вестибюль' (+ 'холл' — проектное правило отделки), 'бассейн', 'палата', 'ремонт', 'водолечебница',
// 'грязелечебница', 'кабинет', 'душ', 'столовая'; у коридора в ремонте 'ремонт' — вторым (отделка ремонта); вид куска
// сети — 'ход' / 'хаб' (+ 'поворот', 'развилка'). У всех — 'только-биом': растут только в биоме «Санаторий».
//
// Свет — плоские плафоны p_san_ceiling_lamp (в коридорах — через 3–4.5 м), в вестибюле — люстра; окна светятся
// холодным «дневным» светом (за окном туман).
import type { Room, RoomElite } from '../model/types';
import { I, room, type Fill, type RoomBuilder } from './roomBuilder';

const C_ITEM = '#2a9d8f';
const C_STASH = '#e76f51';
const NONE: RoomElite[] = [];
const ONLY = 'только-биом';
/** прямой отрезок пола длиннее 9 м (вестибюль 12, бассейн 18): тест пресетов такие пропускает */
const LONG = 'длинный';
/** ширина коридора, м */
const COR = 3;
/** высоты потолка, м: коридор, вестибюль, бассейн, боковое помещение, столовая */
const CEIL_COR = 3.3;
const CEIL_VEST = 4.2;
const CEIL_POOL = 7;
const CEIL_ROOM = 3;
const CEIL_DINING = 3.3;

const meta = (tags: string[], weight: number, note: string) => ({ tags: ['санаторий', ...tags, ONLY], gen: { weight, min: 0, max: 99 }, elite: NONE, note });
/** Своя высота потолка комнаты (Room.ceilM). */
function ceil(r: Room, m: number): Room {
  r.ceilM = m;
  return r;
}

/** Окно с тюлем и портьерами (1.8 м) у стены side от from; под окном — батарея, если radiator. */
function win(b: RoomBuilder, side: 'N' | 'S' | 'W' | 'E', from: number, radiator = false): RoomBuilder {
  b.wall('p_san_window_curtain', side, from);
  if (radiator) b.wall('p_san_radiator', side, from + 0.4);
  return b;
}

/** Мелочь (на тумбочке, на столе): спот 's', группа 'stash'. */
const STASH: Array<[number, Record<string, Fill>]> = [
  [6, {}],
  [2, { s: I('it_kopeyki') }],
  [1, { s: I('it_matches') }],
  [1, { s: I('it_bandage') }],
];
function stash(b: RoomBuilder, x: number, y: number, name: string): RoomBuilder {
  return b.spot('s', name, x, y, 0, 'stash').group('stash', name, C_STASH, STASH);
}

