// Сарай — сеть проходов (биом «Сарай», layout 'tunnels'; рост — src/gen4d/stream.ts, правила — docs/GENERATOR-4D.md
// §17, §19). Замысел пользователя: длинные тёмные проходы — на одной стене гирлянда, с другой стороны стойла; иногда
// вместо стойла — проход дальше. Стойла — как в конюшне: открытые к проходу загоны глубиной 2.4 м, между ними низкие
// перегородки (столб с шаром у прохода, жердь, доски понизу), у задней стены ясли с решёткой для сена. Отделка — доски
// набора пользователя barn-kit (src/data/finishes.ts); перегородки, ясли и гирлянда — модели из примитивов
// (tools/make-barn-props.mjs), прочая мебель — болванки (src/data/props.ts, p_barn_*). Света, кроме гирлянд, нет: биом
// тёмный (Biome.dark).
//
// Куски направлены (stream.ts, barnFlow): проход на южной стене — вход, остальные — выход; за выходом следующий кусок
// встаёт входом, поэтому стойла по всему ходу — по левую руку, гирлянда — по правую.
//
// Кусок прохода — проход 1.5 м (восток) и ряд стойл 2.4 м (запад), всего 3.9 м; стыкуется меткой 'barn' во всю ширину
// прохода (с подвальными ходами не стыкуется). Прямые куски 2, 4, 6, 8 м (стойла по 2 м) и вставка 1 м без стойл (с
// порогом-зазором — шаги 1.1 … 8.1 м: из них складывается любая длина кольца с точностью до клетки), повороты 1.5×1.5 м
// без стойл (направо и налево), развилка — вместо одного стойла проём в задней стене, за ним боковой проход. Гирлянда — по восточной стене
// (сегменты 1 м). Хабы — двор, верхняя комната, конюшня: два–три прохода и лестница-выход ('stair', закрытый выход в
// квартиры).
//
// Теги: первый — 'сарай' (группа спавна и отделка), затем вид куска для роста сети: 'ход' (прямой, поворот, развилка —
// по проёмам), 'хаб'. У всех — 'только-биом' (BIOME_ONLY_TAG, src/gen/generate.ts): сарай растёт только в биоме
// бесконечного мира, в прогонах и прежней прогулке его нет (лестница хаба иначе стыковалась бы с маршами).
import type { Room, RoomElite } from '../model/types';
import { I, room, type RoomBuilder } from './roomBuilder';

const C_STASH = '#e76f51';
const C_ITEM = '#2a9d8f';
const NONE: RoomElite[] = [];
const ONLY = 'только-биом';
/** глубина стойла, ширина прохода, ширина стойла вдоль прохода, м */
const STALL = 2.4;
const AISLE = 1.5;
const BAY = 2;

/** Что лежит в яслях стойла (спот у яслей). */
const MANGER_LOOT: Array<[number, Record<string, ReturnType<typeof I>>]> = [
  [6, {}],
  [2, { m: I('it_samogon') }],
  [1, { m: I('it_kopeyki') }],
  [1, { m: I('it_matches') }],
];

/** Гирлянда вдоль стены side: сегменты по 1 м от from, n штук. */
const garland = (b: RoomBuilder, side: 'N' | 'S' | 'E' | 'W', from: number, n: number): RoomBuilder => {
  for (let k = 0; k < n; k++) b.wall('p_barn_garland', side, from + k);
  return b;
};

// ─────────────────────────────── Куски прохода со стойлами ───────────────────────────────

/**
 * Кусок len м (север — юг): проход у восточной стены (гирлянда), ряд открытых стойл по 2 м у западной; перегородки
 * между стойлами, в каждом — ясли у задней стены и спот «в яслях». open — номер стойла, вместо которого проём в задней
 * стене (боковой проход 'barn').
 */
function stable(id: string, name: string, len: number, weight: number, note: string, open: number | null = null): Room {
  const bays = Math.floor(len / BAY);
  const b = room(id, name, {
    tags: open === null ? ['сарай', 'ход', ONLY] : ['сарай', 'ход', 'развилка', ONLY],
    gen: { weight, min: 0, max: 99 },
    elite: NONE,
    note,
  })
    .rect(0, 0, STALL + AISLE, len)
    .open('N', STALL, 'barn', 'Проход (север)')
    .open('S', STALL, 'barn', 'Проход (юг)');
  if (open !== null) b.open('W', open * BAY + 0.25, 'barn', 'Проход вместо стойла');
  for (let k = 1; k < bays; k++) b.put('p_barn_stall_div', STALL / 2, k * BAY, 0);
  const loot: string[] = [];
  for (let k = 0; k < bays; k++) {
    if (k === open) continue;
    b.wall('p_barn_manger', 'W', k * BAY + 0.4);
    b.spot(`m${k}`, `Ясли ${k + 1}`, 0.75, k * BAY + 1.0, 0, `m${k}`);
    loot.push(`m${k}`);
  }
  for (const key of loot) b.group(key, 'В яслях', C_STASH, MANGER_LOOT.map(([w, v]) => [w, v.m ? { [key]: v.m } : {}]));
  return garland(b, 'E', 0, len).build();
}

/** Вставка без стойл (проход 1.5 м): ею кольца добирают длину до клетки. */
function insert(): Room {
  const b = room('barn_tun_1', 'Проход сарая, 1 м', {
    tags: ['сарай', 'ход', ONLY],
    gen: { weight: 0.3, min: 0, max: 99 },
    elite: NONE,
    note: 'Короткая вставка прохода 1.5×1.0 м без стойл — глухая стена: ею кольца проходов добирают длину до клетки.',
  })
    .rect(0, 0, AISLE, 1)
    .open('N', 0, 'barn', 'Проход (север)')
    .open('S', 0, 'barn', 'Проход (юг)');
  return garland(b, 'E', 0, 1).build();
}

const passes = (): Room[] => [
  insert(),
  stable('barn_tun_2', 'Проход сарая, одно стойло', 2, 1, 'Кусок 3.9×2.0 м: проход 1.5 м и открытое стойло 2.4 м с яслями; гирлянда по другой стене.'),
  stable('barn_tun_4', 'Проход сарая, два стойла', 4, 2, 'Кусок 3.9×4.0 м: проход вдоль двух открытых стойл с перегородкой между ними, ясли у задней стены.'),
  stable('barn_tun_6', 'Длинный проход сарая, три стойла', 6, 2.5, 'Длинный тёмный кусок 3.9×6.0 м: три стойла подряд за перегородками, гирлянда во всю длину.'),
  stable('barn_tun_8', 'Длинный проход сарая, четыре стойла', 8, 2.5, 'Самый длинный кусок 3.9×8.0 м: четыре стойла подряд, гирлянда уходит в темноту.'),
  stable('barn_tun_T', 'Проход вместо стойла', 4, 1, 'Развилка 3.9×4.0 м: первое стойло с яслями, вместо второго — проём 1.5 м в задней стене, за ним проход дальше.', 1),
];

/** Поворот прохода без стойл: вход с юга, выход на восток (направо) или на запад (налево); гирлянда — по внешнему углу. */
function turn(right: boolean): Room {
  const b = room(right ? 'barn_tun_turn' : 'barn_tun_turn_l', right ? 'Поворот прохода сарая направо' : 'Поворот прохода сарая налево', {
    tags: ['сарай', 'ход', 'поворот', ONLY],
    gen: { weight: 0.5, min: 0, max: 99 },
    elite: NONE,
    note: `Г-образный поворот прохода 1.5×1.5 м без стойл: вход с юга, выход ${right ? 'на восток' : 'на запад'} во всю ширину; гирлянда огибает угол.`,
  })
    .rect(0, 0, AISLE, AISLE)
    .open('S', 0, 'barn', 'Проход (юг)')
    .open(right ? 'E' : 'W', 0, 'barn', right ? 'Проход (восток)' : 'Проход (запад)');
  return garland(garland(b, 'N', 0.25, 1), right ? 'W' : 'E', 0.25, 1).build();
}

