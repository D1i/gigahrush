// Спец-комнаты: вход в них переводит игрока в особую сцену со своей механикой (src/locations/,
// docs/LOCATIONS.md). В плане генератора это обычные комнаты; сцену и механику ведёт движок.
import type { Room, RoomElite } from '../model/types';
import { newStairwell } from '../locations/stairwell';
import { LIFT_DOOR_STRAIGHT_M, LIFT_FLOOR_M, LIFT_SHAFT_X, LIFT_SHAFT_Z, newLift } from '../locations/lift';
import { newLair } from '../locations/lair';
import { room } from './roomBuilder';

/** Хвататель: за петлёй — «закрома» и тайники тех, кто не дошёл. Опасность высокая (+20 / +35). */
const ELITE_GRABBER: RoomElite[] = [
  { tierId: 'tier_8', weight: 2 },
  { tierId: 'tier_12', weight: 1 },
];

/** Лифт: на площадке кабины остаётся то, что выронили сброшенные в шахту, — «номенклатура» и изредка «закрома»
 *  (опасность +10 / +20). */
const ELITE_LIFT: RoomElite[] = [
  { tierId: 'tier_5', weight: 3 },
  { tierId: 'tier_8', weight: 1 },
];

/** Логово: тайник спекулянта (опасность +35) — богаче всего, что есть в подъезде. */
const ELITE_LAIR: RoomElite[] = [{ tierId: 'tier_12', weight: 1 }];

/** Id пресета «Бесконечная лестница». */
export const STAIR_LOOP_ID = 'stair_loop';
/** Id пресетов «Ржавый лифт»: А — клетка, Б — каретка. */
export const LIFT_RUSTY_ID = 'lift_rusty';
export const LIFT_CARRIAGE_ID = 'lift_carriage';
/** Id пресета «Логово босса» (заглушка). */
export const BOSS_LAIR_ID = 'boss_lair';

/**
 * «Бесконечная лестница»: пол — внутренность GLB-модуля подъезда пользователя (2.9 × 5.5 м в свету,
 * этаж 3 м), один вход — дверь в передней короткой стене по центру (в GLB: DoorFrame 1.06 м по осям
 * коробки, полотно 0.93 м → проём 1.0 м). Метка 'apt>landing' — та же, что у входных дверей квартир:
 * за дверью квартиры с площадки или коридора может оказаться бесконечная лестница. Декора нет —
 * лестница целиком сцена движка.
 */
function stairLoop(): Room {
  const r = room(STAIR_LOOP_ID, 'Бесконечная лестница', {
    // первый тег — группа «лестница» (страница спавна, отделка подъезда); «спец» и «лестница-петля» — метки локации
    tags: ['лестница', 'спец', 'лестница-петля'],
    gen: { weight: 0.4, min: 0, max: 1 },
    elite: ELITE_GRABBER,
    note:
      'Спец-локация: зацикленный тёмный подъезд (модуль 2.9×5.5 м в свету, этаж 3 м, дверь 1.0 м по центру передней стены). ' +
      'Спуск бесконечен; страшный звук снизу — подняться на этаж, шаг вниз после звука — Хвататель утаскивает. ' +
      'Пережил нужное число звуков подряд — лестница становится обычной и выводит на этаж(и) ниже. Правила — docs/LOCATIONS.md.',
  })
    .rect(0, 0, 2.9, 5.5)
    .open('S', 0.95, 'apt>landing', 'Дверь подъезда (передняя стена)')
    .build();
  r.location = newStairwell();
  return r;
}

/**
 * «Ржавый лифт» — по 3D-ассету пользователя rusted_lift_v2 (docs/LOCATIONS.md §8.9): шахта в плане
 * LIFT_SHAFT_X × LIFT_SHAFT_Z (3.6 × 4.4 м; кабина 2.0 × 3.0 м, узкой стороной к входу), этаж LIFT_FLOOR_M (4.2 м).
 * Два пресета — вид кабины задан явно: «Лифт А» — ржавая клетка (не падает, бьётся о стены), «Лифт Б» — открытая
 * каретка (сильный крен сбрасывает в шахту). У спецификации вид — вероятность cageChance: 1 и 0.
 * Один вход — узкий проём 1.0 м по центру стороны S (в сцене за ним коридор 1.4 м в свету, дверь в мир — у его
 * конца), метка 'apt>landing' — как у входных дверей квартир: дверь шахты на площадке или в коридоре. (С меткой
 * 'corridor' лифт почти не вставал: двустворчатые двери коридоров — магистраль, там сначала ставятся ростовые
 * комнаты.) Выходы кабины на этажах выше: «прямо» — узкий проём над входом (сторона S), «направо» — широкий 2.4 м
 * (сторона E); комнаты за ними ставит StreamWorld.ascend. Декора нет — шахта и кабина целиком сцена движка.
 */
function liftRoom(id: string, name: string, variant: 'cage' | 'carriage'): Room {
  const cage = variant === 'cage';
  const r = room(id, name, {
    // первый тег — группа «лифт» (страница спавна, отделка лифтовых холлов); «спец» и «лифт-шахта» — метки локации
    tags: ['лифт', 'спец', 'лифт-шахта', cage ? 'лифт-клетка' : 'лифт-каретка'],
    // вес и max — замер «Прогулки» (stream.lift.perf.test.ts, docs/LOCATIONS.md §8.1): лифты А и Б вместе (вес 1 + 1)
    // встречаются боту, бродящему наугад, за медиану ~57 шагов; у каждого max 1 на ~10 дверей пути
    gen: { weight: 1, min: 0, max: 1 },
    elite: ELITE_LIFT,
    note:
      (cage
        ? 'Спец-локация: ржавая клетка на тросе — решётки со всех сторон, проёмы спереди и справа. '
        : 'Спец-локация: открытая каретка на стропах — площадка без стен, опаснее клетки. ') +
      `Шахта ${LIFT_SHAFT_X}×${LIFT_SHAFT_Z} м (кабина 2×3 м, этаж ${LIFT_FLOOR_M} м), вход — узкий проём по центру стены. ` +
      'Кнопки на посту — вверх или вниз; на каждом этаже выходы прямо (узкий, над входом) и направо (широкий), за одним ' +
      'из них на одном из этажей — логово. Падающая доска раскачивает кабину: гасить, перебегая на поднявшуюся сторону; ' +
      (cage ? 'клетка бьётся о стены и стоит, пока не стихнет. ' : 'не погасил — сбрасывает в шахту. ') +
      'Правила — docs/LOCATIONS.md.',
  })
    .rect(0, 0, LIFT_SHAFT_X, LIFT_SHAFT_Z)
    .open('S', (LIFT_SHAFT_X - LIFT_DOOR_STRAIGHT_M) / 2, 'apt>landing', 'Вход в шахту (узкий проём 1.0 м)')
    .build();
  r.location = { ...newLift(), cageChance: cage ? 1 : 0 };
  return r;
}

/**
 * «Логово босса» — заглушка: боссов пока нет. Бывшее машинное отделение лифтов на техническом этаже, 6.0 × 4.8 м
 * (типовая машинная комната над шахтами 9-этажки), один проём 1.3 м — туда выводит выход кабины лифта (метка
 * 'corridor'). Сам не растёт (вес 0): ставится только StreamWorld.ascend — за выходом лифта, выпавшим логовом.
 * В «Прогулке» — тёмная комната с табличкой (lairSign).
 */
function bossLair(): Room {
  const r = room(BOSS_LAIR_ID, 'Логово босса (заглушка)', {
    // первый тег — группа «служебное» (страница спавна, отделка технических помещений); «спец», «логово» — метки локации
    tags: ['служебное', 'спец', 'логово'],
    gen: { weight: 0, min: 0, max: 1 },
    elite: ELITE_LAIR,
    note:
      'Спец-локация (заглушка): логово босса за одним из выходов лифта — бывшее машинное отделение 6.0×4.8 м, проём 1.3 м. ' +
      'Темно, красный свет и гул; боссов в игре пока нет — в Room Forge здесь табличка «Здесь будет босс». ' +
      'Вес 0: само не растёт, его ставит только выход лифта. Правила — docs/LOCATIONS.md.',
  })
    .rect(0, 0, 6.0, 4.8)
    .open('S', (6.0 - 1.3) / 2, 'corridor', 'Проём к лифту')
    .build();
  r.location = newLair();
  return r;
}

/** Все спец-комнаты пресетов (свежие объекты при каждом вызове). */
export function buildSpecialRooms(): Room[] {
  return [
    stairLoop(),
    liftRoom(LIFT_RUSTY_ID, 'Ржавый лифт А — клетка', 'cage'),
    liftRoom(LIFT_CARRIAGE_ID, 'Ржавый лифт Б — каретка', 'carriage'),
    bossLair(),
  ];
}
