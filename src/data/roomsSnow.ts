// Снежные тоннели — сеть лазов под снегом (биом «Снежные тоннели», layout 'tunnels'; рост — src/gen4d/stream.ts,
// правила — docs/GENERATOR-4D.md §20). Замысел заказчика: ползём на четвереньках, ходы закручены влево, вправо, вниз
// и вверх, вдаль почти ничего не видно, много ответвлений; выходы в берлоги, где можно стоять скрючившись; обвалы;
// выход из локации — подтаявший снег в полу берлоги (пробить — провалишься в ангар, src/locations/hangar.ts).
//
// Стен у комнат нет: оболочка — полость в снегу (src/view3d/snowMesh.ts) по проёмам комнаты; профиль лаза — устье
// набора пользователя snow-models (арка 1.1 × 0.9 м), берлога — купол 02-snow-den (≈2.1 × 1.4 м в свету). Отделка
// (болванка, движок без полости) — снег (src/data/finishes.ts, f_snow_*).
//
// Лаз стыкуется меткой 'snow' (1.2 м — арка 1.1 м помещается в проём; с ходами подвала и проходами сарая не
// стыкуется): прямые 1, 2, 3, 4 м (с зазором — шаги 1.1 … 4.1 м: из них складываются кольца), горка и яма (пол
// посреди лаза поднимается / опускается — «вверх и вниз»), сдвиг вбок (S-изгиб), повороты — дугой (2 × 2 м) и круче
// (1.6 × 1.6 м), развилки T, Y и крест. Берлоги — тоже куски сети (проходная, угловая, развилка на три лаза), сбоку от
// лаза — тупиковая берлога за боковым лазом ('snow>den' ↔ 'den>snow'). Подтаявшая берлога — хаб сети (тег «хаб»,
// растёт по правилу хабов: не ближе 60 м ползком, к 150 м — наверняка) со спец-локацией «Ангар».
//
// Теги: первый — 'снег' (группа спавна и отделка), 'ход' (лазы и проходные берлоги: длинный обзор, как у подвала), 'берлога' (купол,
// стоять скрючившись), 'лавка' (снежный уступ), 'горка' / 'яма' (+ 'круто'), 'только-биом' (BIOME_ONLY_TAG: только в
// биоме бесконечного мира).
import type { Room, RoomElite } from '../model/types';
import { newHangar } from '../locations/hangar';
import { I, room } from './roomBuilder';

const C_STASH = '#e76f51';
const NONE: RoomElite[] = [];
const ONLY = 'только-биом';
/** Ширина лаза (метка 'snow'), м. */
const W = 1.2;

const crawl = (id: string, name: string, len: number, weight: number, tags: string[], note: string): Room =>
  room(id, name, { tags: ['снег', 'ход', ...tags, ONLY], gen: { weight, min: 0, max: 99 }, elite: NONE, note })
    .rect(0, 0, W, len)
    .open('N', 0, 'snow', 'Лаз (север)')
    .open('S', 0, 'snow', 'Лаз (юг)')
    .build();

function straights(): Room[] {
  return [
    crawl('snow_crawl_1', 'Лаз, 1 м', 1, 0.3, [], 'Короткая вставка лаза 1.2×1.0 м: ею кольца добирают длину до клетки.'),
    crawl('snow_crawl_2', 'Лаз, 2 м', 2, 1, [], 'Лаз 1.2×2.0 м: арка 1.1×0.9 м в свету — только ползком.'),
    crawl('snow_crawl_3_up', 'Лаз с горкой, 3 м', 3, 1.3, ['горка'], 'Лаз 1.2×3.0 м: посередине пол поднимается на 0.25 м — ползёшь вверх, потом вниз.'),
    crawl('snow_crawl_3_down', 'Лаз с ямой, 3 м', 3, 1.3, ['яма'], 'Лаз 1.2×3.0 м: посередине провал на 0.3 м — сползаешь вниз и выбираешься.'),
    crawl('snow_crawl_4_up', 'Крутая горка, 4 м', 4, 0.8, ['горка', 'круто'], 'Лаз 1.2×4.0 м: горб на 0.5 м — лаз уходит вверх под самый наст.'),
    crawl('snow_crawl_4_down', 'Глубокая яма, 4 м', 4, 0.8, ['яма', 'круто'], 'Лаз 1.2×4.0 м: провал на 0.6 м — лаз ныряет вниз и выходит обратно.'),
    room('snow_crawl_jog', 'Лаз со сдвигом', { tags: ['снег', 'ход', ONLY], gen: { weight: 1.2, min: 0, max: 99 }, elite: NONE, note: 'Лаз 1.8×3.0 м: вход и выход сдвинуты на 0.6 м — ход виляет в сторону.' })
      .rect(0, 0, 1.8, 3)
      .open('N', 0, 'snow', 'Лаз (север)')
      .open('S', 0.6, 'snow', 'Лаз (юг)')
      .build(),
    room('snow_crawl_side', 'Лаз с боковым ходом в берлогу', { tags: ['снег', 'ход', ONLY], gen: { weight: 1.4, min: 0, max: 99 }, elite: NONE, note: 'Лаз 1.2×3.0 м: в боковой стене — лаз в тупиковую берлогу (или глухо).' })
      .rect(0, 0, W, 3)
      .open('N', 0, 'snow', 'Лаз (север)')
      .open('S', 0, 'snow', 'Лаз (юг)')
      .open('W', 0.9, 'snow>den', 'Боковой лаз')
      .build(),
  ];
}

