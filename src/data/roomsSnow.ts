/** Находки в берлоге: у лавки (или у стены) — что оставили те, кто полз раньше. */
const STASH: [number, Record<string, ReturnType<typeof I>>][] = [
  [5, {}],
  [2, { s: I('it_matches') }],
  [2, { s: I('it_canned') }],
  [1, { s: I('it_bandage') }],
  [1, { s: I('it_batteries') }],
];

function dens(): Room[] {
  const stash = (b: ReturnType<typeof room>, x: number, y: number) =>
    b.spot('s', 'В берлоге', x, y, 0, 's').group('s', 'В берлоге', C_STASH, STASH.map(([w, v]) => [w, v]));
  return [
    stash(
      room('snow_den_pass', 'Берлога проходная', { tags: ['снег', 'ход', 'берлога', 'лавка', ONLY], gen: { weight: 0.8, min: 0, max: 99 }, elite: NONE, note: 'Берлога 2.6×2.6 м: купол ~1.4 м — стоишь скрючившись; лаз входит и выходит напротив, у стены снежная лавка.' })
        .rect(0, 0, 2.6, 2.6)
        .open('W', 0.7, 'snow', 'Лаз (запад)')
        .open('E', 0.7, 'snow', 'Лаз (восток)'),
      1.3, 2.1,
    ).build(),
    stash(
      room('snow_den_corner', 'Берлога угловая', { tags: ['снег', 'ход', 'берлога', ONLY], gen: { weight: 0.6, min: 0, max: 99 }, elite: NONE, note: 'Берлога 2.6×2.6 м: лаз входит и уходит в сторону — поворот через купол.' })
        .rect(0, 0, 2.6, 2.6)
        .open('S', 0.7, 'snow', 'Лаз (юг)')
        .open('E', 0.7, 'snow', 'Лаз (восток)'),
      0.7, 0.7,
    ).build(),
    stash(
      room('snow_den_junction', 'Берлога на три лаза', { tags: ['снег', 'ход', 'берлога', 'лавка', 'развилка', ONLY], gen: { weight: 0.8, min: 0, max: 99 }, elite: NONE, note: 'Берлога 3.0×3.0 м (концепт набора): купол, три лаза — запад, восток, юг; у северной стены снежная лавка.' })
        .rect(0, 0, 3, 3)
        .open('W', 0.9, 'snow', 'Лаз (запад)')
        .open('E', 0.9, 'snow', 'Лаз (восток)')
        .open('S', 0.9, 'snow', 'Лаз (юг)'),
      1.5, 0.75,
    ).build(),
    stash(
      room('snow_den_side', 'Берлога тупиковая', { tags: ['снег', 'берлога', 'лавка', ONLY], gen: { weight: 1, min: 0, max: 99 }, elite: NONE, note: 'Тупиковая берлога 2.4×2.4 м за боковым лазом: купол и лавка. Обвалы здесь не случаются.' })
        .rect(0, 0, 2.4, 2.4)
        .open('E', 0.6, 'den>snow', 'Лаз из берлоги'),
      0.7, 1.2,
    ).build(),
  ];
}

/** Подтаявшая берлога — выход сети: спец-локация «Ангар». */
function thaw(): Room {
  const r = room('snow_thaw', 'Подтаявшая берлога', {
    tags: ['снег', 'берлога', 'хаб', 'подтаявшая', 'спец', ONLY],
    gen: { weight: 1, min: 0, max: 99 },
    elite: [{ tierId: 'tier_5', weight: 2 }, { tierId: 'tier_8', weight: 1 }],
    note:
      'Хаб сети (через 60–150 м ползком): берлога 3.0×3.0 м, посередине пола — подтаявшее пятно: снег тёмный и мокрый, ' +
      'снизу пробивается тёплый свет ламп ангара, капает. Пробить (E, 3–5 ударов) — провалишься сквозь крышу в ангар ' +
      'промкомплекса (спец-локация «Ангар»). Три лаза — сеть идёт дальше.',
  })
    .rect(0, 0, 3, 3)
    .open('W', 0.9, 'snow', 'Лаз (запад)')
    .open('E', 0.9, 'snow', 'Лаз (восток)')
    .open('N', 0.9, 'snow', 'Лаз (север)')
    .build();
  r.location = newHangar();
  return r;
}

export function buildSnowRooms(): Room[] {
  return [...straights(), ...turns(), ...forks(), ...dens(), thaw()];
}
